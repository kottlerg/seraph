/// Byte offset of the hint section's end indices in a signature.
const HINT_ENDS: usize = SIGNATURE_LEN - K;

/// One more than OMEGA, the largest row end a hint section may hold.
const PAST_OMEGA: u8 = OMEGA.to_le_bytes()[0] + 1;

/// A change to a signature, and the verdict of the changed signature.
type Mutation = (fn(&mut [u8; SIGNATURE_LEN]), VerifyError);

/// A change to the valid external signature, and the check that refuses it.
/// The hint changes rely on that signature's hints: 47 in all (fewer than
/// OMEGA, so the last position slot is free), six in row 0, row ends 6 and 14.
const MUTATIONS: [Mutation; 9] = [
    // A flipped bit of c-tilde.
    (|s| xor_at(s, 0, 1), VerifyError::Mismatch),
    // A row end past OMEGA.
    (
        |s| set_at(s, SIGNATURE_LEN - 1, PAST_OMEGA),
        VerifyError::MalformedHint,
    ),
    // Row 1 ending before row 0.
    (|s| set_at(s, HINT_ENDS + 1, 5), VerifyError::MalformedHint),
    // A non-zero position slot past the last row's end.
    (|s| set_at(s, HINT_ENDS - 1, 1), VerifyError::MalformedHint),
    // Row 0's first two positions swapped, so they decrease.
    (
        |s| swap_at(s, CTILDE_LEN + super::params::L * super::params::POLY_Z_LEN),
        VerifyError::MalformedHint,
    ),
    // z's first coefficient at the norm bound, either sign, and one inside it.
    (|s| set_first_z(s, GAMMA1 - BETA), VerifyError::ZOutOfRange),
    (|s| set_first_z(s, BETA - GAMMA1), VerifyError::ZOutOfRange),
    (|s| set_first_z(s, GAMMA1 - BETA - 1), VerifyError::Mismatch),
    // z's first coefficient at the top of the packed range, GAMMA1.
    (|s| set_first_z(s, GAMMA1), VerifyError::ZOutOfRange),
];

fn xor_at(signature: &mut [u8; SIGNATURE_LEN], index: usize, bits: u8)
{
    if let Some(byte) = signature.get_mut(index)
    {
        *byte ^= bits;
    }
}

fn set_at(signature: &mut [u8; SIGNATURE_LEN], index: usize, value: u8)
{
    if let Some(byte) = signature.get_mut(index)
    {
        *byte = value;
    }
}

fn swap_at(signature: &mut [u8; SIGNATURE_LEN], index: usize)
{
    if let Some([a, b]) = signature
        .get_mut(index..)
        .and_then(|s| s.first_chunk_mut::<2>())
    {
        core::mem::swap(a, b);
    }
}

/// Re-pack z's first coefficient (20 bits at the start of z) as `z`.
fn set_first_z(signature: &mut [u8; SIGNATURE_LEN], z: i32)
{
    let [b0, b1, b2, _] = GAMMA1.wrapping_sub(z).to_le_bytes();
    if let Some([x0, x1, x2]) = signature
        .get_mut(CTILDE_LEN..)
        .and_then(|s| s.first_chunk_mut::<3>())
    {
        (*x0, *x1, *x2) = (b0, b1, (*x2 & 0xf0) | (b2 & 0x0f));
    }
}

/// Run the ML-DSA known-answer tests. Returns the first failing case as an
/// error string, or `Ok(())` if all pass. Compiled in all builds so host and
/// on-target (ktest) runs share identical logic.
///
/// # Errors
///
/// Returns a descriptive `&'static str` on the first mismatch.
pub fn run_ml_dsa_kats() -> Result<(), &'static str>
{
    if verify(
        &EXTERNAL_PUBLIC_KEY,
        &EXTERNAL_MESSAGE,
        &EXTERNAL_CONTEXT,
        &EXTERNAL_SIGNATURE,
    ) != Ok(())
    {
        return Err("ml-dsa: ACVP valid signature refused");
    }
    for kat in &MU_KATS
    {
        if verify_mu(&kat.public_key, &kat.mu, &kat.signature).is_ok() != kat.valid
        {
            return Err("ml-dsa: ACVP mu-interface verdict differs");
        }
    }
    check_context_and_message()?;
    check_signature_changes()
}

/// The valid external case with an over-long context, a changed context and
/// a changed message.
fn check_context_and_message() -> Result<(), &'static str>
{
    let long_context = [0u8; MAX_CONTEXT_LEN + 1];
    if verify(
        &EXTERNAL_PUBLIC_KEY,
        &EXTERNAL_MESSAGE,
        &long_context,
        &EXTERNAL_SIGNATURE,
    ) != Err(VerifyError::ContextTooLong)
    {
        return Err("ml-dsa: over-long context not refused");
    }
    let mut context = EXTERNAL_CONTEXT;
    if let Some(byte) = context.first_mut()
    {
        *byte ^= 1;
    }
    let mut message = EXTERNAL_MESSAGE;
    if let Some(byte) = message.last_mut()
    {
        *byte ^= 0x80;
    }
    if verify(
        &EXTERNAL_PUBLIC_KEY,
        &EXTERNAL_MESSAGE,
        &context,
        &EXTERNAL_SIGNATURE,
    ) != Err(VerifyError::Mismatch)
        || verify(
            &EXTERNAL_PUBLIC_KEY,
            &message,
            &EXTERNAL_CONTEXT,
            &EXTERNAL_SIGNATURE,
        ) != Err(VerifyError::Mismatch)
    {
        return Err("ml-dsa: changed context or message not refused");
    }
    Ok(())
}

/// The valid external case with each change of [`MUTATIONS`], each refused by
/// the check it names.
fn check_signature_changes() -> Result<(), &'static str>
{
    let mut signature = EXTERNAL_SIGNATURE;
    for (mutate, expected) in MUTATIONS
    {
        mutate(&mut signature);
        if verify(
            &EXTERNAL_PUBLIC_KEY,
            &EXTERNAL_MESSAGE,
            &EXTERNAL_CONTEXT,
            &signature,
        ) != Err(expected)
        {
            return Err("ml-dsa: changed signature not refused by its check");
        }
        signature.copy_from_slice(&EXTERNAL_SIGNATURE);
    }
    Ok(())
}
